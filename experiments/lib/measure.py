"""The arithmetic of the measurements, shared by the experiment scripts (experiments/scripts/), the scorers (experiments/score/) and
paper/scripts/, and checked on synthetic data by experiments/tests/measure_test.py (no model).

numpy: clusters (a row and its mirror form one cluster), boot_counts (the row counts of a cluster bootstrap, regenerated by the
scorer from their seed), boot_ratio (a ratio of means with the numerator and denominator on the same resample), interval
(percentile or basic), p_above (a one-sided p-value) and bh (Benjamini-Hochberg). torch: unit, m_sym, lam_boot (lambda_1 of M
on bootstrap resamples, exactly, in the row space of [W; Delta]) and sphere_opt (Adam on an unnormalised v with d = v/|v|).
"""
import numpy as np


def clusters(keys):
    """Cluster ids for rows given (base, source) keys: a row and its mirror (base and source exchanged) form one cluster, every
    other row its own; rows are paired greedily in order, so duplicates pair with duplicates. Returns an int array (n,)."""
    cid, free = [-1] * len(keys), {}
    for i, (b, s) in enumerate(keys):
        j = free.get((s, b), [])
        if j:
            cid[i] = cid[j.pop(0)]
        else:
            cid[i] = i; free.setdefault((b, s), []).append(i)
    return np.array(cid)


def boot_counts(cluster, B=2000, seed=95):
    """Row counts (B, n) of a cluster bootstrap: each resample draws as many clusters as there are, with replacement, and a
    row counts as often as its cluster was drawn (the paper's resampling of mirrored pairs, Section 4.4)."""
    u, inv = np.unique(cluster, return_inverse=True)
    draw = np.random.default_rng(seed).integers(0, len(u), size=(B, len(u)))
    per = np.stack([np.bincount(r, minlength=len(u)) for r in draw])
    return per[:, inv]


def boot_ratio(num, den, C, num_boot=None, den_boot=None):
    """Resampled values of mean(num)/mean(den) under row counts C; either side may come resampled already (lambda_1)."""
    w = C.sum(1)
    nb = C @ num / w if num_boot is None else num_boot
    db = C @ den / w if den_boot is None else den_boot
    return nb / db


def interval(point, r, level=0.95, basic=False):
    """Percentile interval of the resampled values r, or the basic (reverse percentile) interval 2*point - quantiles, which
    corrects a resampling bias such as lambda_1's (convex in M, so pushed up by resampling)."""
    a = (1 - level) / 2; lo, hi = float(np.quantile(r, a)), float(np.quantile(r, 1 - a))
    return (2 * point - hi, 2 * point - lo) if basic else (lo, hi)


def p_above(point, r, bound=1.0):
    """One-sided p-value for "above bound" from a normal approximation with the resampling's standard error (not floored at
    1/(B+1) as a count of resamples would be)."""
    from math import erf, sqrt
    se = float(np.std(r, ddof=1))
    if se == 0:
        return 0.0 if point > bound else 1.0
    z = (point - bound) / se
    return 0.5 * (1 - erf(z / sqrt(2)))


def bh(pvals, q=0.05):
    """Benjamini-Hochberg: which hypotheses are rejected at false-discovery rate q."""
    p = np.asarray(pvals, dtype=float); m = len(p)
    if m == 0:
        return np.zeros(0, bool)
    order = np.argsort(p); ok = p[order] <= q * (np.arange(1, m + 1) / m)
    k = np.max(np.nonzero(ok)[0]) + 1 if ok.any() else 0
    rej = np.zeros(m, bool); rej[order[:k]] = True
    return rej


def unit(v):
    return v / v.norm()


def m_sym(W, D):
    """readout.py's M: sym(W^T D)/n, the product in the inputs' dtype, then float64 (as readout.py computes it)."""
    return 0.5 * (W.T @ D + D.T @ W).double() / W.shape[0]


def lam_boot(W, D, counts):
    """lambda_1 of sym(sum_i c_i w_i Delta_i^T) / sum_i c_i for each row of counts (a torch float64 tensor, resamples x n): the
    resample's own mean, as boot_ratio's numerators use (a cluster bootstrap with clusters of unequal size draws a varying
    number of rows).

    Exact: M_c x = 0 for every x orthogonal to the rows of W and D, so M_c's nonzero spectrum is that of Q^T M_c Q, Q an
    orthonormal basis of a space containing those rows; when that space is smaller than D the complement adds the eigenvalue 0."""
    import torch
    X = torch.cat([W, D]).double()
    Q = torch.linalg.qr(X.T)[0]
    A, Bm = W.double() @ Q, D.double() @ Q
    out = []
    for c in torch.split(counts, 100):
        K = torch.einsum("bi,ij,ik->bjk", c, A, Bm) / c.sum(1)[:, None, None]
        lam = torch.linalg.eigvalsh(0.5 * (K + K.transpose(1, 2)))[:, -1]
        out.append(lam.clamp(min=0) if Q.shape[1] < W.shape[1] else lam)
    return torch.cat(out)


def sphere_opt(loss_of, inits, steps, lr):
    """Adam on an unnormalised vector v per start, the direction being d = v/|v|, from every start at once, keeping each
    start's best iterate (the start included). loss_of maps a (K, D) batch of unit directions to K losses, and each start
    moves only with its own loss (one Adam over the stacked starts updates each coordinate from its own moments, as K separate
    Adams would). The learning rate falls from lr to lr/100 on a cosine. Returns the best direction over all starts and
    iterates, its loss, and per start (name) its best loss, the step it was reached at, and the change over the last 50
    steps."""
    import math
    import torch
    names = [n for n, _ in inits]
    V = torch.stack([unit(d.detach().clone()) for _, d in inits]).requires_grad_(True)
    opt = torch.optim.Adam([V], lr=lr); hist = []
    best_L = torch.full((len(names),), float("inf"), dtype=V.dtype, device=V.device); best_V = V.detach().clone()
    best_step = torch.zeros(len(names), dtype=torch.long, device=V.device)
    for t in range(steps + 1):                                         # no host sync inside the loop
        Dn = V / V.norm(dim=1, keepdim=True); L = loss_of(Dn)
        with torch.no_grad():
            better = L.detach() < best_L
            best_L = torch.where(better, L.detach(), best_L)
            best_V = torch.where(better[:, None], Dn.detach(), best_V)
            best_step = torch.where(better, torch.full_like(best_step, t), best_step)
        hist.append(L.detach())
        if t == steps:
            break
        for g in opt.param_groups:
            g["lr"] = lr * (0.01 + 0.99 * 0.5 * (1 + math.cos(math.pi * t / steps)))
        opt.zero_grad(); L.sum().backward(); opt.step()
    H = torch.stack(hist).cpu()
    rec = [dict(start=n, loss=float(best_L[k]), best_step=int(best_step[k]),
                last50_change=float(H[-51, k] - H[-1, k]) if len(H) > 50 else None) for k, n in enumerate(names)]
    b = int(torch.argmin(best_L))
    return best_V[b].clone(), float(best_L[b]), rec
